"""
Result Writer Module — Serializes crew execution results to canonical files.

After a HyperAgent crew execution completes, this module writes the results
to three canonical files:
  - ./results/latest-summary.md (Markdown summary)
  - ./results/latest-metrics.json (Performance metrics)
  - ./results/latest-report.md (Detailed review report)

These files are then read by the obsidian-sync container for vault integration.

Usage:
  from result_writer import write_execution_results, trigger_obsidian_sync
  
  result = await execute_crew(...)
  await write_execution_results(result, task_id="task-123")
  await trigger_obsidian_sync()  # Triggers docker compose run
"""

import json
import os
import subprocess
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional

logger = logging.getLogger(__name__)

# Results directory (relative to HyperCode-V2.4 root)
RESULTS_DIR = Path(__file__).resolve().parent.parent.parent / "results"
WORKSPACE_DIR = Path(__file__).resolve().parent.parent.parent  # HyperCode-V2.4 root


def ensure_results_dir() -> Path:
    """Ensure the results directory exists."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    return RESULTS_DIR


async def write_execution_results(
    result: Any,
    task_id: str,
    agents: Optional[list[str]] = None,
    duration_seconds: Optional[float] = None,
) -> Dict[str, Path]:
    """
    Write crew execution results to canonical files.

    Args:
        result: The result object from crew.kickoff() or /execute endpoint
        task_id: Task identifier
        agents: List of agents that participated
        duration_seconds: Execution duration for metrics

    Returns:
        Dict mapping file type to file path (summary, metrics, report)
    """
    ensure_results_dir()

    timestamp = datetime.now(timezone.utc).isoformat()
    result_str = str(result) if result else "No output"

    # --- Parse result into structured format ---
    # If result is a dict, use it; otherwise convert to string
    if isinstance(result, dict):
        result_data = result
        summary_text = result.get("message", result_str[:200])
        status = result.get("status", "completed")
    else:
        result_data = {"raw_output": result_str[:500]}
        summary_text = result_str[:200]
        status = "completed"

    # ── Write latest-summary.md ─────────────────────────────────────────────
    summary_file = RESULTS_DIR / "latest-summary.md"
    summary_content = f"""# HyperAgent Loop Summary

**Timestamp:** {timestamp}  
**Task ID:** {task_id}  
**Status:** {status}  
**Agents:** {", ".join(agents) if agents else "none"}  

## Output

{summary_text}

## Raw Result
\`\`\`
{result_str[:500]}
\`\`\`

---

*Synced by crew-orchestrator*
"""

    summary_file.write_text(summary_content, encoding="utf-8")
    logger.info(f"[result_writer] Wrote summary to {summary_file}")

    # ── Write latest-metrics.json ───────────────────────────────────────────
    metrics_file = RESULTS_DIR / "latest-metrics.json"
    metrics_data = {
        "timestamp": timestamp,
        "task_id": task_id,
        "status": status,
        "agents_count": len(agents) if agents else 0,
        "agents": agents or [],
        "duration_seconds": duration_seconds or 0.0,
        "tokens_estimated": len(result_str) // 4 if result_str else 0,
    }

    if isinstance(result_data, dict):
        metrics_data.update(result_data)

    metrics_file.write_text(json.dumps(metrics_data, indent=2), encoding="utf-8")
    logger.info(f"[result_writer] Wrote metrics to {metrics_file}")

    # ── Write latest-report.md ──────────────────────────────────────────────
    report_file = RESULTS_DIR / "latest-report.md"
    report_content = f"""# HyperAgent Execution Report

**Generated:** {timestamp}  
**Task ID:** {task_id}  

## Execution Summary

- **Status:** {status}
- **Duration:** {duration_seconds:.2f}s if duration_seconds else "N/A"
- **Agents:** {len(agents) if agents else 0}
  {f"  - {agents[0] if agents else ''}" if agents else ""}

## Result Details

{json.dumps(result_data, indent=2) if result_data else "No result data"}

## Next Steps

1. Review this report in your Obsidian vault (synced automatically)
2. Decide: promote, iterate, or archive
3. Update WHATSDONE.md if this becomes permanent
4. Document learnings for future runs

---

*Report generated by result_writer.py*
"""

    report_file.write_text(report_content, encoding="utf-8")
    logger.info(f"[result_writer] Wrote report to {report_file}")

    return {
        "summary": summary_file,
        "metrics": metrics_file,
        "report": report_file,
    }


async def trigger_obsidian_sync(dry_run: bool = False) -> bool:
    """
    Trigger the obsidian-sync container to read results and push to vault.

    This runs:
      docker compose -f docker-compose.obsidian-sync.yml run --rm obsidian-sync

    Args:
        dry_run: If True, set DRY_RUN=true (no git push)

    Returns:
        True if sync succeeded, False otherwise
    """
    cwd = WORKSPACE_DIR
    env = os.environ.copy()

    if dry_run:
        env["DRY_RUN"] = "true"

    compose_cmd = [
        "docker",
        "compose",
        "-f",
        "docker-compose.obsidian-sync.yml",
        "run",
        "--rm",
        "obsidian-sync",
    ]

    try:
        logger.info(f"[result_writer] Triggering obsidian-sync from {cwd}")
        logger.info(f"[result_writer] Command: {' '.join(compose_cmd)}")

        # Run synchronously, capture output
        result = subprocess.run(
            compose_cmd,
            cwd=str(cwd),
            env=env,
            capture_output=True,
            text=True,
            timeout=300,  # 5 min timeout
        )

        if result.returncode == 0:
            logger.info("[result_writer] Obsidian sync completed ✅")
            logger.debug(f"[result_writer] stdout:\n{result.stdout}")
            return True
        else:
            logger.error(f"[result_writer] Obsidian sync failed with code {result.returncode}")
            logger.error(f"[result_writer] stderr:\n{result.stderr}")
            return False

    except subprocess.TimeoutExpired:
        logger.error("[result_writer] Obsidian sync timeout (5 min)")
        return False
    except Exception as e:
        logger.error(f"[result_writer] Failed to trigger obsidian-sync: {e}")
        return False


async def write_and_sync(
    result: Any,
    task_id: str,
    agents: Optional[list[str]] = None,
    duration_seconds: Optional[float] = None,
    auto_sync: bool = True,
    dry_run: bool = False,
) -> Dict[str, Any]:
    """
    Convenience function: write results AND trigger sync in one call.

    Args:
        result: Execution result
        task_id: Task ID
        agents: List of agents
        duration_seconds: Execution duration
        auto_sync: If True, automatically trigger obsidian-sync after writing
        dry_run: If True, sync with DRY_RUN=true

    Returns:
        Dict with status and file paths
    """
    files = await write_execution_results(
        result=result,
        task_id=task_id,
        agents=agents,
        duration_seconds=duration_seconds,
    )

    sync_status = None
    if auto_sync:
        sync_status = await trigger_obsidian_sync(dry_run=dry_run)

    return {
        "status": "success",
        "files_written": {k: str(v) for k, v in files.items()},
        "sync_triggered": auto_sync,
        "sync_result": sync_status,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }
